#include "io.h"


// ============================================================
// OUTB
// ============================================================

void outb(uint16_t port, uint8_t value)
{
    __asm__ volatile (
        "outb %0, %1"
        :
        : "a"(value), "Nd"(port)
    );
}


// ============================================================
// INB
// ============================================================

uint8_t inb(uint16_t port)
{
    uint8_t value;

    __asm__ volatile (
        "inb %1, %0"
        : "=a"(value)
        : "Nd"(port)
    );

    return value;
}


// ============================================================
// OUTW
// ============================================================

void outw(uint16_t port, uint16_t value)
{
    __asm__ volatile (
        "outw %0, %1"
        :
        : "a"(value), "Nd"(port)
    );
}


// ============================================================
// INW
// ============================================================

uint16_t inw(uint16_t port)
{
    uint16_t value;

    __asm__ volatile (
        "inw %1, %0"
        : "=a"(value)
        : "Nd"(port)
    );

    return value;
}


// ============================================================
// INSW
// ============================================================

void insw(
    uint16_t port,
    void *buffer,
    uint32_t count
)
{
    __asm__ volatile (
        "cld\n\t"
        "rep insw"
        : "+D"(buffer), "+c"(count)
        : "d"(port)
        : "memory"
    );
}


// ============================================================
// OUTSW
// ============================================================

void outsw(
    uint16_t port,
    const void *buffer,
    uint32_t count
)
{
    __asm__ volatile (
        "cld\n\t"
        "rep outsw"
        : "+S"(buffer), "+c"(count)
        : "d"(port)
        : "memory"
    );
}


// ============================================================
// IO WAIT
// ============================================================

void io_wait(void)
{
    __asm__ volatile (
        "outb %%al, $0x80"
        :
        : "a"(0)
    );
}
